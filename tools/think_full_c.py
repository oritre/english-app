# ---------------------------------------------------------------- right-to-left care
# A formula is shown left to right: a prompt that is only a formula moves to
# `visual` (an LTR line) under a short Hebrew question, and a formula with a
# minus sign inside Hebrew text is wrapped in a left-to-right isolate, so −3
# never shows up as 3−.
import re as _re

_HE = _re.compile('[֐-׿]')
_RUN = _re.compile("[0-9A-Za-z(|−√π][0-9A-Za-z()|.,²³⁰¹⁴-⁹×:+=−<>/°π ]*[0-9A-Za-z)|²³⁰¹⁴-⁹°π]|−[0-9]")


def _iso(s):
    if not isinstance(s, str) or '−' not in s:
        return s
    if not _HE.search(s):
        return '⁦' + s + '⁩' if s[0] in '−(' else s
    return _RUN.sub(lambda m: '⁦' + m.group(0) + '⁩' if '−' in m.group(0) else m.group(0), s)


def _fix(ex):
    p = ex.get('prompt_he')
    if p and not _HE.search(p) and 'visual' not in ex:
        ex['visual'] = p
        ex['prompt_he'] = 'פתרו את המשוואה' if ex.get('before') else ('השלימו' if p.rstrip().endswith(('/?', '?%')) else 'כמה זה?')
    for k in ('prompt_he', 'explain_he', 'hint_he'):
        if k in ex:
            ex[k] = _iso(ex[k])
    if 'body_he' in ex:
        ex['body_he'] = [_iso(b) for b in ex['body_he']]
    if ex['type'] == 'mcq':
        ex['options'] = [_iso(o) if _HE.search(str(o)) else o for o in ex['options']]
        if _HE.search(ex['answer']):
            ex['answer'] = _iso(ex['answer'])
    if ex['type'] == 'buckets':
        for b in ex['buckets']:
            b['label'] = _iso(b['label'])
        for i in ex['items']:
            i['label'] = _iso(i['label'])
    if ex['type'] == 'order' and ex.get('rtl'):
        ex['items'] = [_iso(i) for i in ex['items']]


for _units in FULL.values():
    for _u in _units:
        for _lid, _title, _exs in _u['lessons']:
            for _ex in _exs:
                _fix(_ex)
