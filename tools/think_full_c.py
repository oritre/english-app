def N(prompt, answer, explain, hint=None, **kw):
    """A keypad answer; a negative answer turns on the minus key."""
    if str(answer).startswith('-'):
        kw.setdefault('negative', True)
    return _N(prompt, answer, explain, hint, **kw)


