"""Builds data/think.json and data/lessons/t-*.json: the Brilliant-style courses.

Each lesson teaches by doing: a short idea card, then problems you solve with
your hands (a scale, a pizza, a number line, a robot), each with a hint and an
explanation. Run: python3 tools/think_content.py
"""
