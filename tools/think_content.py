def T(title_he, *body):
    """An idea card. Read aloud in Hebrew."""
    return {'type': 'teach', 'title_he': title_he, 'body_he': list(body), 'say_he': ' '.join((title_he,) + body)}


def _extra(ex, explain, hint, kw):
    if explain:
        ex['explain_he'] = explain
    if hint:
        ex['hint_he'] = hint
    ex.update(kw)
    return ex


def MC(prompt, answer, options, explain, hint=None, **kw):
    return _extra({'type': 'mcq', 'prompt_he': prompt, 'answer': str(answer), 'options': [str(o) if not isinstance(o, dict) else o for o in options]}, explain, hint, kw)


def N(prompt, answer, explain, hint=None, **kw):
    return _extra({'type': 'number', 'prompt_he': prompt, 'answer': str(answer)}, explain, hint, kw)


def BAL(prompt, left, right, answer, explain, hint=None, **kw):
    return _extra({'type': 'balance', 'prompt_he': prompt, 'left': left, 'right': right, 'answer': answer}, explain, hint, kw)


def FR(prompt, parts, answer, explain, hint=None, **kw):
    return _extra({'type': 'fraction', 'prompt_he': prompt, 'parts': parts, 'answer': answer}, explain, hint, kw)


def NL(prompt, lo, hi, step, answer, explain, hint=None, **kw):
    return _extra({'type': 'numberline', 'prompt_he': prompt, 'min': lo, 'max': hi, 'step': step, 'answer': str(answer)}, explain, hint, kw)


def ORD(prompt, items, explain, hint=None, **kw):
    return _extra({'type': 'order', 'prompt_he': prompt, 'items': items}, explain, hint, kw)


def ROBOT(prompt, grid, solution, explain, hint=None, **kw):
    return _extra({'type': 'robot', 'prompt_he': prompt, 'grid': grid, 'solution': solution}, explain, hint, kw)


def SORT(prompt, buckets, items, explain, hint=None, **kw):
    return _extra({'type': 'buckets', 'prompt_he': prompt, 'buckets': [{'id': i, 'label': l} for i, l in buckets],
                   'items': [{'label': l, 'in': b} for l, b in items]}, explain, hint, kw)


def ANG(prompt, answer, explain, hint=None, **kw):
    return _extra({'type': 'angle', 'prompt_he': prompt, 'answer': answer}, explain, hint, kw)


def SIM(prompt, kind, *body):
    return {'type': 'sim', 'prompt_he': prompt, 'kind': kind, 'body_he': list(body)}


def it(icon, n, w=None, adjustable=False, label=None):
    d = {'icon': icon, 'n': n}
    if w is not None:
        d['w'] = w
    if adjustable:
        d['adjustable'] = True
    if label is not None:
        d['label'] = label
    return d


def scale(left, right, tilt='even'):
    return {'left': left, 'right': right, 'tilt': tilt}


def bars(*rows):
    return [{'parts': p, 'shaded': s, 'label': l} for p, s, l in rows]


