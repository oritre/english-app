"""Film courses added to two existing topics: מלכים ובית המקדש (grades 4-7) and ידע לחיים (grades 1-4).

Kings: in Tanach order, following pshat, Rashi and Chazal and the traditional chronology (the First
Temple stood 410 years; seventy years of exile in Bavel). God is never shown; at most a soft light from
above. Golyat is told as faith, with the stone and the sling and no death shown; the episode of
Bat-Sheva is left out; the calves of Yerovam are told as a sin and never shown; the fire on the Carmel
is only light. The destruction is told briefly, through aftermath and landscape.

Life: practical knowledge for young kids (road, clock, home safety, hygiene, money, derech eretz,
friendship), each tied to a pasuk or a saying of Chazal, inside an ordinary religious family at home.
"""
from know_films import S, Q, L, U, course


def sv(l2, l3=None):
    """Kings narration: level 2, and (optionally) what level 3 adds after the level-2 lines."""
    d = {2: l2}
    if l3 is not None:
        d[3] = l2 + l3
    return d


def sl(l1, l2):
    """Life narration: level 1 and level 2."""
    return {1: l1, 2: l2}


